import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
const outPath = resolve(here, "../src/generated.ts");

const installSh = readFileSync(resolve(repoRoot, "install.sh"), "utf8");
const agentsEn = readFileSync(resolve(repoRoot, "AGENTS.md"), "utf8");
const agentsZh = readFileSync(resolve(repoRoot, "AGENTS.zh-CN.md"), "utf8");

const content = `// Auto-generated by scripts/embed.mjs — do not edit manually.
export const INSTALL_SH: string = ${JSON.stringify(installSh)};
export const AGENTS_EN: string = ${JSON.stringify(agentsEn)};
export const AGENTS_ZH: string = ${JSON.stringify(agentsZh)};
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, content, "utf8");
console.log("Embedded install.sh, AGENTS.md, and AGENTS.zh-CN.md into src/generated.ts");
